-- ============================================================
-- Prijslijsten v2 — herstructureren naar quality + carpet_dimension
-- ============================================================
-- Achtergrond:
-- v1 (`20260503_price_lists.sql`) maakte price_list_lines met
-- (price_list_nr, article_number, price_cents) waarbij article_number =
-- {QUALITY}-{COLOR}-{SAMPLE_DIM}. Dat is verkeerd: een sticker op een
-- staal moet de carpet-prijzen tonen voor die kwaliteit, niet één
-- staal-prijs. Bovendien bleven prijzen 0 omdat sample_dim != carpet_dim.
--
-- v2 model:
--   price_list_lines (price_list_nr, quality_id, carpet_dimension_id, price_cents)
--   UNIQUE (price_list_nr, quality_id, carpet_dimension_id)
--
-- Stickers tonen per sample alle (carpet_dim, prijs) rijen voor die
-- kwaliteit + de prijslijst van de klant.
--
-- Verder:
--   - Maakt prijslijsten 0150 (BENELUX) en 0151 (BENELUX INCL. MV) aan
--   - Backfillt 001/0150/0151 met huidige quality_base_prices als
--     basisprijs (gebruiker kan 0151 aanpassen wanneer specifieke
--     marketing-vergoeding-tarieven beschikbaar zijn)
--   - Koppelt klanten op basis van client_number (uit klantenbestanden
--     'klantenbestand prijslijst 150.xlsx' en '...151.xlsx')
-- ============================================================

-- ─── 1. Schema-migratie price_list_lines ──────────────────

DROP TABLE IF EXISTS price_list_lines CASCADE;

CREATE TABLE price_list_lines (
  id                   uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  price_list_nr        text NOT NULL REFERENCES price_lists(nr) ON DELETE CASCADE,
  quality_id           uuid NOT NULL REFERENCES qualities(id) ON DELETE CASCADE,
  carpet_dimension_id  uuid NOT NULL REFERENCES carpet_dimensions(id) ON DELETE CASCADE,
  price_cents          integer NOT NULL DEFAULT 0,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  UNIQUE (price_list_nr, quality_id, carpet_dimension_id)
);

CREATE INDEX idx_pll_list_quality ON price_list_lines(price_list_nr, quality_id);
CREATE INDEX idx_pll_quality      ON price_list_lines(quality_id);

DROP TRIGGER IF EXISTS price_list_lines_updated_at ON price_list_lines;
CREATE TRIGGER price_list_lines_updated_at
  BEFORE UPDATE ON price_list_lines
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

ALTER TABLE price_list_lines ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS price_list_lines_authenticated_all ON price_list_lines;
CREATE POLICY price_list_lines_authenticated_all
  ON price_list_lines FOR ALL TO authenticated USING (true) WITH CHECK (true);

-- ─── 2. Prijslijsten 0150 + 0151 aanmaken ─────────────────

INSERT INTO price_lists (nr, name, valid_from, active) VALUES
  ('0150', 'Benelux per 01.07.2022',          DATE '2022-07-01', true),
  ('0151', 'Benelux incl. MV per 01.07.2022', DATE '2022-07-01', true)
ON CONFLICT (nr) DO UPDATE SET
  name = EXCLUDED.name,
  valid_from = EXCLUDED.valid_from,
  active = EXCLUDED.active;

-- ─── 3. Backfill regels uit quality_base_prices ───────────
-- Identieke baselineprijzen voor 001, 0150 en 0151. De gebruiker kan
-- 0151 aanpassen wanneer de marketing-vergoeding-tarieven beschikbaar zijn.

INSERT INTO price_list_lines (price_list_nr, quality_id, carpet_dimension_id, price_cents)
SELECT pl.nr, qbp.quality_id, qbp.carpet_dimension_id, qbp.price_cents
FROM   quality_base_prices qbp
CROSS JOIN (VALUES ('001'), ('0150'), ('0151')) AS pl(nr)
WHERE  qbp.price_cents > 0
  AND  qbp.carpet_dimension_id IS NOT NULL  -- m²-prijzen voor afwijkende maten passen niet in deze tabel
ON CONFLICT (price_list_nr, quality_id, carpet_dimension_id) DO NOTHING;

